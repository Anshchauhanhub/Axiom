export const getCategoryForGoal = (title = '', categoryName = '') => {
  if (categoryName) {
    const match = STUDY_CATEGORIES.find(c => c.name.toLowerCase() === categoryName.toLowerCase());
    if (match) return match;
  }

  const lowerTitle = (title || '').toLowerCase().trim();
  if (!lowerTitle) return STUDY_CATEGORIES.find(c => c.id === 7) || STUDY_CATEGORIES[0];

  let bestMatch = null;
  let maxKwLength = 0;

  // Search for the longest matching keyword across ALL categories
  for (const cat of STUDY_CATEGORIES) {
    for (const kw of cat.keywords) {
      const lowerKw = kw.toLowerCase();
      // Match exact word or boundary substring
      if (lowerTitle.includes(lowerKw)) {
        if (lowerKw.length > maxKwLength) {
          maxKwLength = lowerKw.length;
          bestMatch = cat;
        }
      }
    }
  }

  if (bestMatch) {
    return bestMatch;
  }

  if (lowerTitle.includes("exam") || lowerTitle.includes("prep") || lowerTitle.includes("test")) {
    return STUDY_CATEGORIES.find(c => c.id === 14) || STUDY_CATEGORIES[0];
  }

  // General tech/learning default is Computer Science (ID 7) instead of Mathematics
  return STUDY_CATEGORIES.find(c => c.id === 7) || STUDY_CATEGORIES[0];
};
